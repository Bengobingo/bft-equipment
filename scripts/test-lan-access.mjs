import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const base = process.env.BFT_TEST_LAN_URL;
assert(base, "Set BFT_TEST_LAN_URL to an isolated LAN test server.");
const address = new URL(base);
assert(address.protocol === "http:" && address.port !== "3000" && /^(10\.|192\.168\.|172\.(1[6-9]|2\d|3[01])\.)/.test(address.hostname), "Use an isolated private IPv4 server, never production port 3000.");
const credentials = JSON.parse(readFileSync(process.env.BFT_TEST_CREDENTIALS, "utf8").replace(/^\uFEFF/, ""));
let cookie = "", checks = 0;
async function api(path, method = "GET", body, expected = 200, origin = base) {
  const response = await fetch(base + "/api/" + path, { method, headers: { Cookie: cookie, ...(method === "GET" ? {} : { Origin: origin, "Content-Type": "application/json" }) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const data = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
  if (response.headers.get("set-cookie")) cookie = response.headers.get("set-cookie").split(";")[0];
  checks++;
  return data;
}
assert.equal((await api("health")).application, "bft-equipment");
const page = await fetch(base);
assert.equal(page.status, 200);
const html = await page.text();
const asset = html.match(/(?:src|href)="([^"?#]+\.js)/)?.[1];
assert(asset, "Application JavaScript asset should be served from this LAN origin.");
const assetUrl = new URL(asset, base);
assert.equal(assetUrl.origin, address.origin);
assert.equal((await fetch(assetUrl)).status, 200); checks += 4;
await api("state", "GET", undefined, 401);
await api("login", "POST", credentials, 403, "http://untrusted.example");
await api("login", "POST", credentials);
assert.match(cookie, /^bft_session=/); checks++;
const state = await api("state");
assert.equal(state.user.username, credentials.username); checks++;
const name = `LAN verification ${crypto.randomUUID()}`;
await api("equipment", "POST", { name, category: "主機板測試設備箱", model: "LAN", location: "Test only", condition: "ready", notes: "Isolated LAN test", components: [{ id: "lan-part", type: "CPU", name: "LAN CPU", specification: "LAN test", partNumber: "LAN-PN", quantity: 1 }] });
assert((await api("state")).equipment.some(row => row.name === name)); checks++;
await api("logout", "POST", {}, 403, "http://untrusted.example");
assert.equal((await api("state")).user.username, credentials.username); checks++;
await api("logout", "POST", {});
await api("state", "GET", undefined, 401);
console.log(`LAN integration passed: ${checks} checks (page/assets, login/cookie, read/write, logout and cross-origin rejection).`);
