import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { readFileSync } from "node:fs";
const source = new URL("../drizzle/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", source), "utf8"));
const db = new DatabaseSync(":memory:"); db.exec("PRAGMA foreign_keys=ON");
for (const migration of journal.entries.filter(row => row.idx < 7)) db.exec(readFileSync(new URL(migration.tag + ".sql", source), "utf8"));
db.exec(`INSERT INTO users(id,username,name,email,department,role,password,created) VALUES('u','qa','QA','','QA','admin','qa','2026-10-28');
INSERT INTO equipment(id,code,name,category,brand,model,serial,location,condition,notes,components,created) VALUES('e','BOX001','Existing box','主機板測試設備箱','','QA','','Rack','ready','','[]','2026-10-28');
INSERT INTO loans(id,equipment_id,user_id,department,start,end,purpose,status,created,updated,returned,return_note,return_check) VALUES('l','e','u','QA','2026-10-28','2026-10-28','Existing historical return','returned','2026-10-28','2026-10-28','2026-10-28','Original inspection','[]');`);
const original = JSON.stringify(db.prepare("SELECT * FROM loans").all());
db.exec(readFileSync(new URL("0007_return_inspection.sql", source), "utf8"));
assert.equal(JSON.stringify(db.prepare("SELECT * FROM loans").all()), original);
assert.equal(db.prepare("SELECT count(*) AS n FROM return_requests").get().n, 0);
db.exec("INSERT INTO return_requests(id,loan_id,requester_id,requested) VALUES('r','l','u','2026-10-28')");
assert.throws(() => db.exec("INSERT INTO return_requests(id,loan_id,requester_id,requested) VALUES('r2','l','u','2026-10-28')"), /UNIQUE/);
db.exec("UPDATE return_requests SET status='rejected' WHERE id='r'");
db.exec("INSERT INTO return_requests(id,loan_id,requester_id,requested) VALUES('r2','l','u','2026-10-28')");
assert.equal(db.prepare("SELECT count(*) AS n FROM return_requests").get().n, 2);
assert.equal(db.prepare("PRAGMA foreign_key_check").all().length, 0);
const existingRequests = JSON.stringify(db.prepare("SELECT * FROM return_requests").all());
db.exec(readFileSync(new URL("0008_return_self_check.sql", source), "utf8"));
const migratedRequests = db.prepare("SELECT * FROM return_requests").all();
assert(migratedRequests.every(row => row.self_check === null));
assert.equal(JSON.stringify(migratedRequests.map(row => { const saved = { ...row }; delete saved.self_check; return saved; })), existingRequests);
assert.equal(JSON.stringify(db.prepare("SELECT * FROM loans").all()), original);
const selfCheck = [{ id: "cpu", quantity: 2, condition: "ok", checked: true }];
db.prepare("UPDATE return_requests SET self_check=? WHERE id='r2'").run(JSON.stringify(selfCheck));
assert.deepEqual(JSON.parse(db.prepare("SELECT self_check FROM return_requests WHERE id='r2'").get().self_check), selfCheck);
assert.equal(db.prepare("SELECT self_check FROM return_requests WHERE id='r'").get().self_check, null);
db.close(); console.log("Return migration passed: historical data preserved, one active request per loan and retry history supported; self-check migration preserves existing records and stores new checklists.");
