import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
const migration = readFileSync(new URL("../drizzle/0005_box_equipment_codes.sql", import.meta.url), "utf8");
const db = new DatabaseSync(":memory:");
db.exec("PRAGMA foreign_keys=ON; CREATE TABLE equipment(id TEXT PRIMARY KEY,code TEXT UNIQUE NOT NULL,created TEXT NOT NULL); CREATE TABLE loans(id TEXT PRIMARY KEY,equipment_id TEXT REFERENCES equipment(id));");
const add = db.prepare("INSERT INTO equipment VALUES (?,?,?)");
add.run("a", "PED-0001", "2026-10-27"); add.run("b", "PED-0002", "2026-10-27"); add.run("c", "PED-0003", "2026-10-27");
add.run("manual", "CUSTOM-A", "2026-10-27"); add.run("malformed", "PED-12A", "2026-10-27");
db.exec("INSERT INTO loans VALUES('loan-a','a')");
db.exec(migration);
const rows = () => db.prepare("SELECT id,code FROM equipment ORDER BY id").all();
const code = id => db.prepare("SELECT code FROM equipment WHERE id=?").get(id).code;
assert.equal(code("a"), "BOX001"); assert.equal(code("b"), "BOX002"); assert.equal(code("c"), "BOX003");
assert.equal(code("manual"), "CUSTOM-A"); assert.equal(code("malformed"), "PED-12A");
assert.equal(db.prepare("SELECT e.code FROM loans l JOIN equipment e ON e.id=l.equipment_id").get().code,"BOX001");
const before = rows(); db.exec(migration); assert.deepEqual(rows(), before);
add.run("existing", "BOX010", "2026-10-28"); add.run("legacy", "PED-KIT-001", "2026-10-28");
db.exec(migration); assert.equal(code("existing"),"BOX010"); assert.equal(code("legacy"),"BOX011");
const nextCode = () => db.prepare("SELECT printf('BOX%03d',COALESCE(MAX(CAST(SUBSTR(code,4) AS INTEGER)),0)+1) AS code FROM equipment WHERE code GLOB 'BOX[0-9]*' AND SUBSTR(code,4) NOT GLOB '*[^0-9]*'").get().code;
assert.equal(nextCode(),"BOX012"); add.run("large","BOX999","2026-10-28"); assert.equal(nextCode(),"BOX1000");
assert.deepEqual(db.prepare("PRAGMA foreign_key_check").all(), []);
db.close(); console.log("Box code tests passed: 12 checks (migration, links, custom codes, collisions, repeat execution and 999 rollover).");
